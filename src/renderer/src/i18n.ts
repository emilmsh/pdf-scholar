const DICTIONARIES: Record<Lang, Dict> = { nb, en }

export function resolveLanguage(pref: LanguagePreference): Lang {
  if (pref !== 'auto') return pref
  const sys = (navigator.language || 'en').toLowerCase()
  return sys.startsWith('nb') || sys.startsWith('nn') || sys.startsWith('no') ? 'nb' : 'en'
}

let current: Lang = 'nb'
const listeners = new Set<() => void>()

export function setLanguage(pref: LanguagePreference): void {
  const next = resolveLanguage(pref)
  if (next === current) return
  current = next
  for (const cb of listeners) cb()
}

export function getLanguage(): Lang {
  return current
}

/** Subscribe a component to language changes (needed because several
 *  components are memoized and won't re-render via prop cascades). */
export function useLang(): Lang {
  return useSyncExternalStore(
    (cb) => {
      listeners.add(cb)
      return () => listeners.delete(cb)
    },
    () => current
  )
}

export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  let out = DICTIONARIES[current][key]
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value))
    }
  }
  return out
}

/** Locale for date formatting etc. */
export function locale(): string {
  return current === 'nb' ? 'nb-NO' : 'en-GB'
}

/** The text to show for a failure that came back over IPC.
 *
 *  main and shared cannot reach this module, so a recognised failure travels as a
 *  CODE and gets translated here. Anything else — an fs error, a provider's own
 *  message — keeps its text, because that detail is the whole value and no
 *  invented translation could carry it. Every toast that shows an engine failure
 *  goes through this, so an English user never reads a Norwegian fragment inside
 *  a translated sentence. */
export function errorText(e: FileError): string {
  if (!e.code) return e.error
  // Two prefixes because the two families read differently: `engine.*` entries
  // are lowercase fragments spliced into a toast sentence, `aierr.*` entries are
  // whole sentences shown on their own in a chat bubble.
  return isAiErrorCode(e.code) ? t(`aierr.${e.code}`) : t(`engine.${e.code}`)
}

const isAiErrorCode = (code: NonNullable<FileError['code']>): code is AiErrorCode =>
  code.startsWith('ai-')
