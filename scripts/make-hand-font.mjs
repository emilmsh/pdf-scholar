// Regenerates the handwriting-font modules in src/shared/ from TrueType files.
//
// A handwriting font ships as base64 inside a source module rather than as a
// file on disk, because THREE targets need the same bytes and only one of them
// has a filesystem: Electron main (desktop engine), the renderer (browser
// engine + the on-screen webfont) and the extension. A bundled constant is the
// one form that works in all three without an asset pipeline or a packaging
// rule to get wrong. Each font gets its OWN module so each is a separate lazy
// chunk — a session that never touches a note written in the old pen never
// fetches it (see src/shared/hand-note.ts).
//
//   node scripts/make-hand-font.mjs [caveat|patrickhand]      (default: all)
//
// The sources in assets/fonts/ are SUBSETS, not the upstream files, and that is
// deliberate: PDFium does no OpenType shaping (it looks glyphs up through the
// cmap and nothing else) while a browser turns `calt` on by default. Caveat's
// contextual alternates would therefore give the on-screen overlay different
// glyphs AND different widths than the saved file — the exact reflow this
// module exists to prevent. Subsetting also cuts the bytes PDFium copies
// verbatim into /FontFile2, so every saved document gets smaller.
//
// Regenerate a subset from upstream with (fontTools' pyftsubset):
//
//   pyftsubset <upstream.ttf> --output-file=assets/fonts/<Name>-subset.ttf \
//     --unicodes=U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,\
// U+02DA,U+02DC,U+0100-017F,U+0180-024F,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,\
// U+02DD-02FF,U+0304,U+0308,U+0329,U+1E00-1E9F,U+1EF2-1EFF,U+2000-206F,U+2074,\
// U+20A0-20BF,U+2113,U+2122,U+2191,U+2193,U+2212,U+2215,U+2C60-2C7F,U+A720-A7FF,\
// U+FEFF,U+FFFD \
//     --layout-features= --name-IDs='*' --notdef-outline \
//     --drop-tables+=DSIG,FFTM,GSUB,GPOS,GDEF
//
// (latin + latin-ext, so æøå and the rest of Latin Extended-A survive.) The
// checks below refuse anything that is not a static glyf-outline TrueType with
// no layout tables, so a re-run against the wrong file fails loudly instead of
// shipping a font the two renderings disagree about.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

/** The fonts we ship. `caveat` is the pen notes are written with today;
 *  `patrickhand` is kept because notes written before the swap recorded it and
 *  must be re-baked in their own font (see hand-note.ts). */
const FONTS = {
  caveat: {
    file: 'Caveat-Regular-subset.ttf',
    out: 'hand-font-data-caveat.ts',
    name: 'Caveat',
    credit: 'Caveat by Impallari Type — https://github.com/googlefonts/caveat',
    licence: 'assets/fonts/Caveat-OFL.txt'
  },
  patrickhand: {
    file: 'PatrickHand-Regular-subset.ttf',
    out: 'hand-font-data-patrickhand.ts',
    name: 'Patrick Hand',
    credit:
      'Patrick Hand by Patrick Wagesreiter — https://github.com/google/fonts/tree/main/ofl/patrickhand',
    licence: 'assets/fonts/PatrickHand-OFL.txt'
  }
}

/** sfnt table directory: [tag, ...] — enough to prove what is and is not there */
function sfntTables(bytes) {
  const tables = []
  const numTables = bytes.readUInt16BE(4)
  for (let i = 0; i < numTables; i++) {
    tables.push(bytes.toString('latin1', 12 + i * 16, 16 + i * 16))
  }
  return tables
}

function build(id) {
  const font = FONTS[id]
  const src = join(ROOT, 'assets', 'fonts', font.file)
  const out = join(ROOT, 'src', 'shared', font.out)

  const bytes = readFileSync(src)
  const tag = bytes.readUInt32BE(0)
  if (tag !== 0x00010000 && tag !== 0x74727565) {
    console.error(`${src} is not a TrueType font (sfnt tag 0x${tag.toString(16)})`)
    process.exit(1)
  }
  const tables = sfntTables(bytes)
  if (!tables.includes('glyf')) {
    // A CFF/OTF outline fails both this check and FPDF_FONT_TRUETYPE.
    console.error(`${src} has no 'glyf' table — CFF outlines cannot be embedded this way`)
    process.exit(1)
  }
  if (tables.includes('fvar')) {
    // google/fonts ships Caveat only as the variable Caveat[wght].ttf. A
    // variable font in a PDF is a font with no defined instance.
    console.error(`${src} is a VARIABLE font (has 'fvar') — use the static Regular`)
    process.exit(1)
  }
  for (const layout of ['GSUB', 'GPOS']) {
    if (tables.includes(layout)) {
      console.error(
        `${src} still has a ${layout} table. PDFium does no shaping and the browser does: ` +
          `strip the layout features (see the pyftsubset command in this file's header).`
      )
      process.exit(1)
    }
  }

  const b64 = bytes.toString('base64')
  writeFileSync(
    out,
    `// GENERATED by scripts/make-hand-font.mjs — do not edit by hand.
//
// ${basename(src)}, SIL Open Font License 1.1.
// ${font.credit}
// Licence text: ${font.licence} (must ship with the font).
// Subset to latin + latin-ext with the layout features stripped, because
// PDFium does no shaping and a browser does — see the generator's header.
//
// base64 rather than a file: Electron main, the renderer and the extension all
// need these exact bytes and only one of them can read from disk. Its own
// module so it is its own lazy chunk.
export const HAND_FONT_NAME = '${font.name}'
export const HAND_FONT_BASE64 =
  '${b64}'
`,
    'utf8'
  )
  console.log(
    `wrote ${out}  (${(bytes.length / 1024).toFixed(0)} kB font -> ${(b64.length / 1024).toFixed(0)} kB base64)`
  )
}

const which = process.argv[2]
if (which && !FONTS[which]) {
  console.error(`unknown font '${which}' — one of: ${Object.keys(FONTS).join(', ')}`)
  process.exit(1)
}
for (const id of which ? [which] : Object.keys(FONTS)) build(id)
