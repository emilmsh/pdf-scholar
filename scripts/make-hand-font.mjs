// Regenerates src/shared/hand-font-data.ts from a TrueType file.
//
// The handwriting font ships as base64 inside a source module rather than as a
// file on disk, because THREE targets need the same bytes and only one of them
// has a filesystem: Electron main (desktop engine), the renderer (browser
// engine + the on-screen webfont) and the extension. A bundled constant is the
// one form that works in all three without an asset pipeline or a packaging
// rule to get wrong.
//
//   node scripts/make-hand-font.mjs [path-to.ttf]
//
// Default source: Patrick Hand Regular (SIL Open Font License 1.1) —
// https://github.com/google/fonts/tree/main/ofl/patrickhand
// The licence text lives beside it in assets/fonts/PatrickHand-OFL.txt and
// MUST stay in the repo: the OFL requires the copyright notice to travel with
// the font, including when it is embedded.
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = process.argv[2] ?? join(ROOT, 'assets', 'fonts', 'PatrickHand-Regular.ttf')
const out = join(ROOT, 'src', 'shared', 'hand-font-data.ts')

const bytes = readFileSync(src)
const tag = bytes.readUInt32BE(0)
if (tag !== 0x00010000 && tag !== 0x74727565) {
  console.error(`${src} is not a TrueType font (sfnt tag 0x${tag.toString(16)})`)
  process.exit(1)
}

const b64 = bytes.toString('base64')
writeFileSync(
  out,
  `// GENERATED by scripts/make-hand-font.mjs — do not edit by hand.
//
// ${basename(src)}, SIL Open Font License 1.1.
// Patrick Hand by Patrick Wagesreiter — https://github.com/google/fonts/tree/main/ofl/patrickhand
// Licence text: assets/fonts/PatrickHand-OFL.txt (must ship with the font).
//
// base64 rather than a file: Electron main, the renderer and the extension all
// need these exact bytes and only one of them can read from disk. See the
// generator's header for the full reasoning.
export const HAND_FONT_NAME = 'Patrick Hand'
export const HAND_FONT_BASE64 =
  '${b64}'
`,
  'utf8'
)
console.log(`wrote ${out}  (${(bytes.length / 1024).toFixed(0)} kB font -> ${(b64.length / 1024).toFixed(0)} kB base64)`)
